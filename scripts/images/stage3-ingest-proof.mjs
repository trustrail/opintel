import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync,chmodSync} from 'node:fs';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';

// External synthetic fixture only. Customer-file contents never enter an image.
export function configureIngest(directory,projectId,sourceId,hostAddress){
 const zone=join(directory,'ingest','zone');mkdirSync(zone);chmodSync(zone,0o777);
 const party={id:randomUUID(),projectId,code:'supplier',name:'Synthetic supplier',active:true,decimalSeparator:'.',dateFormat:'YYYY-MM-DD'};
 const rule={id:randomUUID(),projectId,partyId:party.id,active:true,matchKind:'filename_regex',pattern:'^supplier_(?<period>2026-03)\\.csv$',kind:'inventory',periodGroup:'period',priority:1,sheetIndex:1,headerRow:1,periodAsAtFormat:'month_end'};
 writeFileSync(join(directory,'landing-rules.json'),JSON.stringify({filingParties:[party],rules:[rule]}),{mode:0o644});
 const file=join(directory,'service.json'),config=JSON.parse(readFileSync(file,'utf8'));
 config.receiptUrl=`https://${hostAddress}:13811`;
 config.landingZones=[{projectId,sourceId,directory:'/ingest/zone',stateFile:'/ingest/register.json',rulesFile:'/config/landing-rules.json',pollMs:1000,landing:{name:'acceptance_landing',credentialRef:'secret://acceptance/source',strategy:'append_as_at'}}];
 writeFileSync(file,JSON.stringify(config),{mode:0o644});
 const state=()=>JSON.parse(readFileSync(join(directory,'ingest','register.json'),'utf8'));
 return {
  async arriveOffline(wait){
   await wait(()=>assert.equal(state().filings.length,0),'Empty landing history');
   writeFileSync(join(zone,'supplier_2026-03.csv'),'quantity\n100\n',{mode:0o644});
   return wait(()=>{const records=state().filings;assert.equal(records.length,1);const filing=records[0];assert.ok(filing.landing);assert.equal(filing.landing.registered,false);assert.equal(filing.landing.receipt.rowCount,1);assert.equal(filing.deliveredRevision??0,0);return filing;},'Offline customer commit with pending receipt');
  },
  async afterReplacement(wait,previous){
   await wait(()=>{const current=state().filings;assert.equal(current.length,1);assert.equal(current[0].id,previous.id);assert.equal(current[0].sha256,previous.sha256);assert.deepEqual(current[0].landing.receipt,previous.landing.receipt);assert.equal(current[0].landing.registered,false);assert.equal(current[0].deliveredRevision??0,0);},'Preserved offline landing history');
  },
  async delivered(wait,previous,gatewayQuery,sourceQuery){
   await wait(()=>{const current=state().filings;assert.equal(current.length,1);assert.equal(current[0].id,previous.id);assert.deepEqual(current[0].landing.receipt,previous.landing.receipt);assert.equal(current[0].landing.registered,true);assert.equal(current[0].deliveredRevision,current[0].revision);},'Durable receipt delivery');
   assert.equal(gatewayQuery(`SELECT count(*) FROM landing_receipt WHERE filing_id='${previous.id}'`),'1');
   assert.equal(gatewayQuery(`SELECT count(*) FROM arrival_notice WHERE filing_id='${previous.id}' AND payload->>'outcome'='landed'`),'1');
   // Receipt table is generated by the product; enforce identifier syntax before SQL.
   assert.match(previous.landing.receipt.landedTable,/^"[a-z_][a-z0-9_]*"\."[a-z_][a-z0-9_]*"$/u);
   assert.equal(sourceQuery(`SELECT count(*) FROM ${previous.landing.receipt.landedTable}`),'1');
   return {offlineCommit:true,pendingSurvivedReplacement:true,sameFilingId:true,receiptDelivered:true,customerRowCount:1,filingId:previous.id};
  },
 };
}
